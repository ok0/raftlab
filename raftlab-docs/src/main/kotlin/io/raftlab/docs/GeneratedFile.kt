package io.raftlab.docs

/**
 * One generated Markdown file.
 *
 * @property path File name relative to the output directory, for example `election.md`; always `/`-separated and never absolute.
 * @property content Full file text with `\n` line endings and exactly one trailing newline.
 */
public data class GeneratedFile(
    val path: String,
    val content: String,
)
