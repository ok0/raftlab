package io.raftlab.docs

import io.raftlab.viz.MermaidLint
import io.raftlab.viz.ModuleGraph
import io.raftlab.viz.ModuleGraphRenderer
import java.nio.file.Files
import java.nio.file.Path

/**
 * Generates the committed Mermaid Markdown docs from a fixed, ordered list of entries, and the architecture region of the README.
 *
 * Every diagram is rendered and linted in memory before anything is written, so a lint failure never leaves partial output.
 * Output is deterministic: the same code and the same module graph always produce byte-identical files.
 */
public object DocsGenerator {
    /** First line of every generated file. */
    public const val HEADER: String = "<!-- GENERATED by ./gradlew generateDocs. Do not edit. -->"

    /** Line that opens the generated architecture region of the README. */
    internal const val README_BEGIN: String = "<!-- BEGIN GENERATED:architecture -->"

    /** Line that closes the generated architecture region of the README. */
    internal const val README_END: String = "<!-- END GENERATED:architecture -->"

    /**
     * Generates all docs in memory.
     *
     * @param moduleGraph Module graph read from `build/raftlab/module-graph.json`; drives the module and architecture docs.
     * @return The generated files in entry order.
     * @throws IllegalStateException if a diagram fails Mermaid lint.
     */
    public fun generate(moduleGraph: ModuleGraph): List<GeneratedFile> = render(DocEntries.standard(moduleGraph))

    /**
     * Generates all docs and writes them into [outDir], creating the directory if needed, then rewrites the architecture region of [readme].
     *
     * Existing files that are not generated are left untouched. Everything is rendered and checked before anything is written.
     *
     * @param outDir Directory to write the generated files into.
     * @param moduleGraph Module graph read from `build/raftlab/module-graph.json`.
     * @param readme README file that holds the architecture markers.
     * @return The generated files in entry order.
     * @throws IllegalStateException if a diagram fails Mermaid lint or the README lacks its markers; nothing is written in that case.
     */
    public fun write(
        outDir: Path,
        moduleGraph: ModuleGraph,
        readme: Path,
    ): List<GeneratedFile> {
        val files = render(DocEntries.standard(moduleGraph))
        val region = readmeRegion(readme, moduleGraph)
        writeFiles(outDir, files)
        Files.writeString(readme, region.second)
        return files
    }

    /**
     * Compares the files in [outDir] and the architecture region of [readme] with freshly generated docs without writing anything.
     *
     * @param outDir Directory holding the committed generated files.
     * @param moduleGraph Module graph read from `build/raftlab/module-graph.json`.
     * @param readme README file that holds the architecture markers.
     * @return One problem text per missing, differing or unexpected `*.md` file, and one for a stale README region; empty when up to date.
     * @throws IllegalStateException if a diagram fails Mermaid lint or the README lacks its markers.
     */
    public fun check(
        outDir: Path,
        moduleGraph: ModuleGraph,
        readme: Path,
    ): List<String> {
        val problems = check(outDir, generate(moduleGraph)).toMutableList()
        val region = readmeRegion(readme, moduleGraph)
        if (region.first != region.second) {
            problems += "differs: ${readme.fileName}\n" +
                UnifiedDiff.diff(readme.fileName.toString(), region.first, region.second)
        }
        return problems
    }

    internal fun render(entries: List<DocEntry>): List<GeneratedFile> {
        if (entries.map { it.fileName }.toSet().size != entries.size) {
            throw IllegalArgumentException("duplicate generator entry file names")
        }
        var blockNumber = 0
        return entries.map { e ->
            val blocks = e.blocks()
            for (block in blocks) {
                blockNumber++
                if (block is DocEntry.Mermaid) {
                    val errors = MermaidLint.lint(block.text)
                    if (errors.isNotEmpty()) {
                        val details = errors.joinToString("\n") { "  line ${it.line}: ${it.message}" }
                        throw IllegalStateException(
                            "Mermaid lint failed for ${e.fileName} (block $blockNumber):\n$details",
                        )
                    }
                }
            }
            GeneratedFile(e.fileName, markdown(e, blocks))
        }
    }

    internal fun write(
        outDir: Path,
        entries: List<DocEntry>,
    ): List<GeneratedFile> {
        val files = render(entries)
        writeFiles(outDir, files)
        return files
    }

    internal fun check(
        outDir: Path,
        files: List<GeneratedFile>,
    ): List<String> {
        val problems = mutableListOf<String>()
        for (f in files) {
            val p = outDir.resolve(f.path)
            if (!Files.isRegularFile(p)) {
                problems += "missing: ${f.path} (expected generated file does not exist)"
            } else {
                val actual = String(Files.readAllBytes(p), Charsets.UTF_8)
                if (actual != f.content) {
                    problems += "differs: ${f.path}\n" + UnifiedDiff.diff(f.path, actual, f.content)
                }
            }
        }
        if (Files.isDirectory(outDir)) {
            val expectedNames = files.map { it.path }.toSet()
            val entries = Files.list(outDir).use { s -> s.toList() }
            val unexpected =
                entries
                    .filter { Files.isRegularFile(it) }
                    .map { it.fileName.toString() }
                    .filter { it.endsWith(".md") && it !in expectedNames }
                    .sorted()
            for (name in unexpected) {
                problems += "unexpected: $name (not produced by the generator; delete it or add a generator entry)"
            }
        }
        return problems
    }

    internal fun readmeRegion(
        readme: Path,
        moduleGraph: ModuleGraph,
    ): Pair<String, String> {
        val overview = ModuleGraphRenderer.overview(moduleGraph)
        val errors = MermaidLint.lint(overview)
        if (errors.isNotEmpty()) {
            val details = errors.joinToString("\n") { "  line ${it.line}: ${it.message}" }
            throw IllegalStateException("Mermaid lint failed for ${readme.fileName}:\n$details")
        }
        if (!Files.isRegularFile(readme)) {
            throw IllegalStateException(
                "README not found: $readme (it must contain the lines $README_BEGIN and $README_END)",
            )
        }
        val actual = String(Files.readAllBytes(readme), Charsets.UTF_8)
        val begin = actual.indexOf(README_BEGIN)
        if (begin < 0) throw IllegalStateException("${readme.fileName}: missing marker $README_BEGIN")
        val end = actual.indexOf(README_END, begin + README_BEGIN.length)
        if (end < 0) {
            throw IllegalStateException("${readme.fileName}: missing marker $README_END after $README_BEGIN")
        }
        val expected =
            actual.substring(0, begin + README_BEGIN.length) +
                "\n```mermaid\n" + overview.trimEnd('\n') + "\n```\n" +
                actual.substring(end)
        return actual to expected
    }

    private fun writeFiles(
        outDir: Path,
        files: List<GeneratedFile>,
    ) {
        Files.createDirectories(outDir)
        for (f in files) {
            Files.write(outDir.resolve(f.path), f.content.toByteArray(Charsets.UTF_8))
        }
    }

    private fun markdown(
        e: DocEntry,
        blocks: List<DocEntry.Block>,
    ): String =
        buildString {
            append(HEADER).append("\n# ").append(e.title).append("\n\n")
            append(e.description).append("\n")
            for (block in blocks) {
                append("\n")
                when (block) {
                    is DocEntry.Mermaid -> append("```mermaid\n").append(block.text.trimEnd('\n')).append("\n```\n")
                    is DocEntry.Markdown -> append(block.text.trimEnd('\n')).append("\n")
                }
            }
        }
}
